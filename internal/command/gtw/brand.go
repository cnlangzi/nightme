package gtw

import "regexp"

// nightmeSite is the canonical NightMe product URL. The issue
// footer (/gtw new) and the PR body footer (/gtw pr) both link
// the brand to it. Code builds its links from this constant;
// comments and docs spell the URL out literally.
const nightmeSite = "https://nightme.dev"

// summaryHeading is the opening heading of every PR body. It is
// plain text: the brand link belongs to the footer, not to the
// heading.
const summaryHeading = "## Summary by NightMe"

// summaryHeadingLinkedPrefix is the linked variant of the heading.
// normalizeSummaryHeading rewrites it to summaryHeading, so the
// heading never carries a link.
const summaryHeadingLinkedPrefix = "## Summary by [NightMe]("

// brandLine is the NightMe signature that closes a generated issue
// or PR body. The NightMe name links to nightmeSite.
const brandLine = "_Generated by [NightMe](" + nightmeSite + ")_"

// brandFooter is the closed footer of a generated issue or PR
// body: a horizontal rule, then the brand signature. The rule
// keeps the signature separate from the text above it — directly
// under a text line Markdown would read it as a setext heading
// underline.
const brandFooter = "\n\n---\n" + brandLine + "\n"

// brandLinkRegex matches a markdown link whose text is the
// NightMe brand name, with any target: `[NightMe](https://…)`.
// Stripping it reduces the linked variant of the summary heading
// to the plain one.
var brandLinkRegex = regexp.MustCompile(`(?i)\[nightme\]\([^)]*\)`)
