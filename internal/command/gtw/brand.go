package gtw

import (
	"regexp"
	"strings"
)

// nightmeSite is the canonical NightMe product URL. The issue
// footer (/gtw new) and the PR body footer (/gtw pr) both link
// the brand to it. Code builds its links from this constant;
// comments and docs spell the URL out literally.
const nightmeSite = "https://nightme.dev"

// summaryHeading is the opening heading of every PR body. It is
// plain text: the brand link belongs to the footer, not to the
// heading.
const summaryHeading = "## Summary by NightMe"

// summaryHeadingLinkedPrefix is the linked variant of the heading.
// normalizeSummaryHeading rewrites it to summaryHeading, so the
// heading never carries a link.
const summaryHeadingLinkedPrefix = "## Summary by [NightMe]("

// brandFooter is the signature stamped at the bottom of every
// generated issue and PR body: a blank line, a horizontal rule, and
// the brand link. The blank line keeps "---" a horizontal rule;
// directly under a text line Markdown would read it as a setext
// heading underline.
const brandFooter = "\n\n---\n_Generated by [NightMe](" + nightmeSite + ")_\n"

// brandFooterLineRe matches a signature line the agent wrote itself,
// in any link variant. appendBrandFooter drops those lines and
// stamps the canonical footer instead.
var brandFooterLineRe = regexp.MustCompile(`(?m)^[ \t]*[*_]*Generated by \[?NightMe\]?(\([^)]*\))?[*_]*[ \t]*\r?$`)

// appendBrandFooter stamps the brand signature at the bottom of a
// generated body.
//
// Why this lives in Go instead of the agent prompt: the brand link
// is a mechanical property of the body. A model that paraphrases
// the signature — dropping the link, or pointing it at a stale
// target — would otherwise ship an unbranded body, and the
// regression would only show up on some PRs. Doing it in code is
// deterministic and zero-cost, the same reasoning as
// appendClosesFooter.
//
// A signature line the agent wrote itself is dropped first, so the
// body ends with exactly one canonical footer.
func appendBrandFooter(body string) string {
	body = brandFooterLineRe.ReplaceAllString(body, "")
	return strings.TrimRight(body, " \t\r\n") + brandFooter
}
